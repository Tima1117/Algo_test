"""Класс активов фонда по названию.

В реестре Банка России у всех действующих розничных открытых и биржевых фондов одна категория —
«рыночных финансовых инструментов», поэтому для фильтра и сводов «Рынка» нужен свой класс.
Правило — по ключевым словам в названии фонда, по порядку: первое совпадение побеждает
(«Индекс МосБиржи государственных облигаций» — облигации, а не акции).
"""
from __future__ import annotations

import re

RULES: list[tuple[str, tuple[str, ...]]] = [
    # сначала однозначные слова, потом общие («Акции с выплатой дохода» — акции, а не облигации)
    ("Денежный рынок", ("денежн", "ликвидн", "сбережен", "сберегат", "накопительн", "сейф", "кэш", "cash",
                        "казначейск", "ключевой", "процент", "резервн", "чистые деньги")),
    ("Золото и металлы", ("золот", "драгоцен", "металл", "серебр", "gold", "финголд", "платин", "паллади")),
    ("Облигации", ("облигац", "долгов", "бонд", "купон", "вдо", "рантье", "флоатер", "офз", "инфляцион")),
    ("Акции", ("акци", "дивиденд", "голуб", "эшелон", "фишек", "отрасл", "нефтегаз", "природн", "сырьев",
               "технолог", "интеллект", "айпио", "ipo", "инновац", "размещени", "энергет", "потребит", "импульс",
               "агро", "китай", "ресурс", "недра", "оборонн", "мировые рынки", "исламск", "халяльн", "квант",
               "новые имена", "великолепная")),
    ("Смешанные", ("сбаланс", "смешан", "баланс", "вечн", "всепогод", "моя цель", "моя пенсия", "пенсион",
                   "стратеги", "консерват", "осторожн", "разумн", "лежебок", "умный", "взвешен", "бережн",
                   "портфел", "универсальн")),
    ("Валютные инструменты", ("валют", "юан", "доллар")),
    ("Облигации", ("доход",)),
    ("Акции", ("индекс", "рост", "лидер", "компани", "финанс")),
]
OTHER = "Не определён по названию"


def asset_class(name: str) -> str:
    n = re.sub(r"\s+", " ", (name or "").lower().replace("ё", "е"))
    for label, words in RULES:
        if any(w in n for w in words):
            return label
    return OTHER
